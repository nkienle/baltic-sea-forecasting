# Standard library
from typing import Union

# Third-party
import matplotlib.pyplot as plt
import torch
import wandb

# First-party
from neural_lam import metrics, utils
from neural_lam.models.ar_prob_model import ARProbModel
from neural_lam.models.graph_diff import GraphDiff

# Local
from ..config import NeuralLAMConfig
from ..datastore import BaseDatastore


STOCHASTICITY_SOURCES = ("fgn", "mc", "sdl")


class GraphCRPS(ARProbModel):
    """
    Continuous Ranked Probability Score (CRPS) Model.

    Ensemble members are generated by one or more sources of stochasticity
    in the GraphDiff backbone, which is shared with graph_det/EDM/FM/SI
    (--stochasticity, any combination):
    * fgn: a random noise vector z, embedded and fed to every conditional
        layer norm (as in FGN). Without fgn, z is the constant
        --deterministic_noise_value, as in graph_det.
    * mc: MC dropout in the MLPs of the GNNs (U-Cast, arXiv:2604.09041),
        active also at inference.
    * sdl: stochastic decomposition layers, Gaussian noise added to the
        mesh node representations on each level of the hierarchy (Schreck
        et al., arXiv:2512.18815), see GraphDiff.add_level_noise.
    All noise is drawn from the global RNG (see ARProbModel.on_fit_start), so
    that it is reproduced in the gradient checkpointing recomputation.

    All sources are scaled by a noise ramp r in [0, 1] (fgn: z = c + r eps,
    mc: p = r p_target, sdl: amplitude r alpha), which rises linearly over the
    first --stoch_warmup_epochs of training (counted from
    crps_stage_start_epoch, set by the crps_finetune scheduler). At r = 0 the
    model is exactly graph_det, so CRPS fine-tuning of a graph_det
    checkpoint starts from the deterministic model. Validation and test
    always use r = 1.

    Like graph_fm, graph_det and GraphEFM, each member is predicted as a
    normalized residual that is rescaled by the one-step difference
    statistics, added to the previous state and clamped to the valid range.
    """

    supports_distr_crps = True

    def __init__(
        self,
        args,
        config: NeuralLAMConfig,
        datastore: BaseDatastore,
        datastore_boundary: Union[BaseDatastore, None],
        datastore_atmosphere: Union[BaseDatastore, None],
        **kwargs,
    ):
        super().__init__(
            args,
            config,
            datastore,
            datastore_boundary,
            datastore_atmosphere,
            **kwargs,
        )
        self.val_metrics.update(
            {
                "ens_crps": [],
            }
        )

        if args.backbone_model == "graph_diff":
            print("Using GraphDiff")
            self.model = GraphDiff(
                args,
                config,
                datastore,
                datastore_boundary,
                datastore_atmosphere,
            )
        else:
            raise NotImplementedError(
                f"Unknown backbone model: {args.backbone_model}"
            )

        # Compute indices and define clamping functions, matching
        # BaseGraphModel (and thereby graph_fm) and GraphEFM
        self.prepare_clamping_params(config, datastore)

        # Sources of stochasticity
        # (args of checkpoints from before --stochasticity: fgn)
        self.stochasticity = set(getattr(args, "stochasticity", ["fgn"]))
        unknown = self.stochasticity - set(STOCHASTICITY_SOURCES)
        if unknown:
            raise ValueError(
                f"Unknown --stochasticity {sorted(unknown)}, choose from "
                f"{STOCHASTICITY_SOURCES}"
            )
        if not self.stochasticity:
            utils.rank_zero_print(
                "GraphCRPS: no --stochasticity given, all ensemble members "
                "are identical (deterministic model)"
            )
        if "sdl" in self.stochasticity:
            self.model.add_level_noise(args)
        self.mc_dropout_p = (
            args.mc_dropout_p if "mc" in self.stochasticity else 0.0
        )
        self._mc_dropout_mlps = []
        if self.mc_dropout_p > 0.0:
            for module in self._mc_dropout_modules(args.mc_dropout_scope):
                self._mc_dropout_mlps += utils.set_mc_dropout(
                    module, self.mc_dropout_p
                )
        utils.rank_zero_print(
            f"GraphCRPS: stochasticity {sorted(self.stochasticity)}"
            + (
                f", MC dropout p={self.mc_dropout_p} in "
                f"{len(self._mc_dropout_mlps)} MLPs "
                f"({args.mc_dropout_scope})"
                if self._mc_dropout_mlps
                else ""
            )
        )

        # Noise ramp, see class docstring. crps_stage_start_epoch is set by
        # the crps_finetune scheduler (first epoch of CRPS fine-tuning)
        self.stoch_warmup_epochs = getattr(args, "stoch_warmup_epochs", 0)
        self.crps_stage_start_epoch = 0
        self._train_stoch_ramp = 1.0
        self._applied_stoch_ramp = None
        # Set by the crps_finetune scheduler (--freeze_backbone_epochs): only
        # the SDL parameters are updated
        self.freeze_backbone = False

    def _mc_dropout_modules(self, scope):
        """The backbone submodules whose MLPs get MC dropout"""
        net = self.model
        if net.hierarchical:
            processor = [
                net.mesh_down_gnns,
                net.mesh_down_same_gnns,
                net.mesh_up_gnns,
                net.mesh_up_same_gnns,
            ]
            mesh = [net.mesh_init_gnns, net.mesh_read_gnns]
        else:
            processor, mesh = [net.processor_gnns], []
        if scope == "processor":
            return processor
        if scope == "mesh":
            return processor + mesh
        if scope == "all":
            return [net]
        raise ValueError(f"Unknown --mc_dropout_scope {scope}")

    @property
    def stoch_ramp(self):
        """Current noise ramp r (1 outside of training)"""
        return self._train_stoch_ramp if self.training else 1.0

    def _apply_stoch_ramp(self):
        """Push the noise ramp into the MC dropout and SDL modules"""
        ramp = self.stoch_ramp
        if ramp == self._applied_stoch_ramp:
            return ramp
        for mlp in self._mc_dropout_mlps:
            mlp.mc_dropout_p = ramp * self.mc_dropout_p
        self.model.sdl_scale = ramp
        self._applied_stoch_ramp = ramp
        return ramp

    def on_train_batch_start(self, batch, batch_idx):
        if self.stoch_warmup_epochs > 0:
            num_batches = self.trainer.num_training_batches
            if not num_batches or num_batches == float("inf"):
                num_batches = 1
            # (batch_idx + 1: r > 0 already in the first step, so that the
            # SDL parameters are used in every step, as plain DDP requires)
            progress = (
                self.current_epoch
                - self.crps_stage_start_epoch
                + (batch_idx + 1) / num_batches
            ) / self.stoch_warmup_epochs
            self._train_stoch_ramp = float(min(max(progress, 0.0), 1.0))
        else:
            self._train_stoch_ramp = 1.0
        return super().on_train_batch_start(batch, batch_idx)

    def on_after_backward(self):
        super().on_after_backward()
        if self.freeze_backbone:
            # Drop the backbone gradients rather than setting requires_grad,
            # so that the optimizer (and its state) covers the same
            # parameters in all phases. Optimizers skip parameters without
            # gradient.
            for name, param in self.named_parameters():
                if not name.startswith("model.sdl."):
                    param.grad = None

    def on_train_epoch_end(self):
        super().on_train_epoch_end()
        if torch.cuda.is_available() and self.global_rank == 0:
            print(
                "[graph_crps] peak GPU memory "
                f"{torch.cuda.max_memory_allocated() / 2**30:.1f} GiB "
                f"(ar_steps_train {self.trainer.datamodule.ar_steps_train}, "
                f"grad checkpointing {self.grad_checkpointing}, "
                f"distributed CRPS {self.train_distr_crps})",
                flush=True,
            )

    def on_save_checkpoint(self, checkpoint):
        super().on_save_checkpoint(checkpoint)
        checkpoint["crps_stage_start_epoch"] = self.crps_stage_start_epoch

    def on_load_checkpoint(self, checkpoint):
        """
        Allow loading a checkpoint without the SDL parameters (e.g. of
        graph_det or of graph_crps without sdl): these keep their
        initialisation. Any other mismatch still fails the (strict) load.
        """
        loaded_state_dict = checkpoint["state_dict"]
        new_keys = [
            key
            for key, value in self.state_dict().items()
            if key.startswith("model.sdl.") and key not in loaded_state_dict
        ]
        if new_keys:
            own_state_dict = self.state_dict()
            for key in new_keys:
                loaded_state_dict[key] = own_state_dict[key].detach().clone()
            utils.rank_zero_print(
                f"GraphCRPS: {len(new_keys)} SDL parameter tensors not in the "
                "checkpoint, keeping their initialisation"
            )
        super().on_load_checkpoint(checkpoint)

    def predict_step(
        self,
        prev_state,
        prev_prev_state,
        forcing,
        boundary_forcing,
        atmosphere_forcing,
    ):
        """
        Step state one step ahead using prediction model, X_{t-1}, X_t -> X_t+1
        prev_state: (B, num_grid_nodes, feature_dim), X_t
        prev_prev_state: (B, num_grid_nodes, feature_dim), X_{t-1}
        forcing: (B, num_grid_nodes, forcing_dim)
        boundary_forcing: (B, num_boundary_nodes, boundary_forcing_dim)
        atmosphere_forcing: (B, num_atmosphere_nodes, atmosphere_forcing_dim)


        Returns:
        next_state: (B, N_grid, d_state),
            predicted weather state X_{t+1} at time t+1
        pred_std: (B, N_grid, d_state) if output_std, else None
        """
        if prev_prev_state is not None:
            input_grid = torch.cat(
                (prev_state, prev_prev_state, forcing), dim=-1
            )
        else:
            input_grid = torch.cat((prev_state, forcing), dim=-1)
        # (B, N_grid, d_input)

        ramp = self._apply_stoch_ramp()

        # Noise vector for the conditional layer norms. Drawn from the global
        # RNG, so that it is the same in the gradient checkpointing
        # recomputation (unlike a separate torch.Generator)
        z = torch.full(
            (prev_state.shape[0], self.model.noise_dim),
            float(self.args.deterministic_noise_value),
            device=prev_state.device,
        )
        if "fgn" in self.stochasticity and ramp > 0.0:
            z = z + ramp * torch.randn_like(z)

        net_output = self.model(
            input_grid,
            noise_level=z,
            cond=None,
            boundary_forcing=boundary_forcing,
            atmosphere_forcing=atmosphere_forcing,
        )  # (B, N_grid, d_grid_out)

        # NOTE: From here on this is identical to BaseGraphModel.predict_step
        # (graph_fm) and to graph_det, so that all models sharing the GraphDiff
        # backbone use the same residual parametrization and the same output
        # clamping. --pred_residual has no effect here, the residual
        # parametrization is always used.
        if self.output_std:
            pred_delta_mean, pred_std_raw = net_output.chunk(
                2, dim=-1
            )  # both (B, num_grid_nodes, d_f)
            # NOTE: The predicted std. is not scaled in any way here
            # linter for some reason does not think softplus is callable
            # pylint: disable-next=not-callable
            pred_std = torch.nn.functional.softplus(pred_std_raw)
        else:
            pred_delta_mean = net_output
            pred_std = None

        # Rescale with one-step difference statistics
        rescaled_delta_mean = pred_delta_mean * self.diff_std + self.diff_mean

        # Clamp values to valid range (also add the delta to the previous state)
        new_state = self.get_clamped_new_state(rescaled_delta_mean, prev_state)

        return new_state, pred_std

    def training_step(self, batch):
        """
        Train on single batch
        batch consists of:
        init_states: (B, 2, num_interior_nodes, d_features)
        target_states: (B, pred_steps, num_interior_nodes, d_features)
        forcing: (B, pred_steps, num_interior_nodes, d_forcing),
        boundary_forcing:
            (B, pred_steps, num_boundary_nodes, d_boundary_forcing),
            where index 0 corresponds to index 1 of init_states
        """
        (
            init_states,
            target_states,
            forcing,
            boundary_forcing,
            atmosphere_forcing,
            _,
        ) = batch

        # NOTE: We always use ensemble size 2 for training (following FGN)
        trajectories = self.sample_trajectories(
            init_states,
            forcing,
            boundary_forcing,
            atmosphere_forcing,
            ensemble_size=1 if self.train_distr_crps else 2,
        )

        if self.train_distr_crps:
            # CRPS computed across one member per device
            pred_forecast = trajectories[:, 0]  # Extract single forecast
            crps_batch = self.compute_distributed_crps(
                pred_forecast, target_states
            )
        else:
            # CRPS computed across multiple members on same device
            crps_batch = metrics.afcrps_ens(
                trajectories,
                target_states,
                None,
                average_grid=False,
                sum_vars=False,
                alpha=self.args.crps_alpha,
            )  # (B, pred_steps, d_f)
            # prediction: (B, pred_steps, num_interior_nodes, d_f)
            # pred_std: (B, pred_steps, num_interior_nodes, d_f) or (d_f,)
            # loss_batch: (B, pred_steps)

        loss_batch = metrics.mask_and_reduce_metric(
            crps_batch / self.per_var_std,
            mask=self.loss_mask,
            average_grid=True,
            sum_vars=True,
        )

        # Compute loss - mean over unrolled times and batch
        batch_loss = torch.mean(loss_batch)

        # The distributed CRPS is scaled by 2 for the gradients (see
        # compute_distributed_crps), log the actual CRPS
        logged_loss = (
            batch_loss.detach() / 2
            if self.train_distr_crps
            else batch_loss.detach()
        )
        log_dict = {
            "train_loss": logged_loss,
            "stoch_ramp": torch.tensor(
                self._train_stoch_ramp, device=batch_loss.device
            ),
        }
        self.log_dict(
            log_dict,
            prog_bar=True,
            on_step=True,
            on_epoch=True,
            sync_dist=True,
            batch_size=batch[0].shape[0],
        )
        return batch_loss

    def validation_step(self, batch, *args):
        """
        Run validation on single batch
        """
        super().validation_step(batch, *args)
        batch_idx = args[0]
        (
            trajectories,
            target_states,
            spread_squared_batch,
            ens_mse_batch,
        ) = self.ensemble_step(batch)
        self.val_metrics["spread_squared"].append(spread_squared_batch)
        self.val_metrics["ens_mse"].append(ens_mse_batch)
        crps_batch = metrics.crps_ens(
            trajectories,
            target_states,
            None,
            mask=self.loss_mask,
            average_grid=True,
            sum_vars=False,
        )
        self.val_metrics["ens_crps"].append(crps_batch)
        # Scalar ensemble CRPS (normalized units, mean over lead times and
        # variables), monitored for the min_val_crps checkpoint
        self.log(
            "val_mean_ens_crps",
            torch.mean(crps_batch),
            on_step=False,
            on_epoch=True,
            sync_dist=True,
            batch_size=batch[0].shape[0],
        )

        if (
            self.trainer.is_global_zero
            and batch_idx == 0
            and self.n_example_pred > 0
        ):
            # For now use val_steps_to_log to determine which steps
            # to make these plots for
            plot_log_steps = list(
                filter(
                    lambda s: s <= target_states.shape[1],
                    self.args.val_steps_to_log,
                )
            )
            # Plot forecasts
            traj_plots = self.plot_ensemble_examples(
                batch,
                n_examples=self.n_example_pred,
                prediction=trajectories,
                time_steps=plot_log_steps,
                log=False,
            )

            # Store plots
            log_plot_dict = {}
            log_plot_dict.update(
                {
                    f"prior_{plot_key}": plot
                    for plot_key, plot in traj_plots.items()
                }
            )

            if not self.trainer.sanity_checking:
                # Log all plots to wandb
                wandb.log(log_plot_dict)

            plt.close("all")
